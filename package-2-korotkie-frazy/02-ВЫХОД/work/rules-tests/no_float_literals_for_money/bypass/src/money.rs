//! Формальный обход: плавающая точка записана экспонентой.
//! Границы слова вокруг мантиссы нет, поэтому проверка на `\d+\.\d+`
//! может не сработать — требование §2.1 нарушено.

pub fn discounted(total_minor: i64) -> i64 {
    let rate = 1.5e-3;
    total_minor - total_minor * (rate * 1e3) as i64
}
