//! Формальный обход: запрещённая библиотека используется под переименованным
//! крейтом `ah`. В исходнике нет привычных форм обращения к оригинальному имени,
//! поэтому правило по токену может не сработать — требование §3.2 нарушено.

use ah::{bail, Result};

pub fn settle(amount: i64) -> Result<()> {
    if amount <= 0 {
        bail!("amount must be positive");
    }
    Ok(())
}
