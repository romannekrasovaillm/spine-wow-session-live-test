//! Формальный обход: арифметика с плавающей точкой есть, но имя типа не названо —
//! литерал `0.985` имеет выведенный плавающий тип. Требование §2.1 нарушено,
//! правило по имени типа может не сработать.

pub fn discounted(total_minor: i64) -> i64 {
    let rate = 0.985;
    total_minor / 100 * (rate * 100.0) as i64
}
